-- Function 8A: Safe Concurrent Seat Initialization using Advisory Lock
CREATE OR REPLACE FUNCTION public.ensure_train_seats_initialized(
    p_train_id TEXT,
    p_travel_date DATE,
    p_class_code TEXT
)
RETURNS INT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_total_seats INT := 24;
    v_seats_per_row INT := 8;
    v_berth_types TEXT[] := ARRAY['LOWER', 'MIDDLE', 'UPPER', 'SIDE_LOWER', 'SIDE_UPPER', 'WINDOW', 'AISLE'];
    v_berth_count INT := array_length(v_berth_types, 1);
    v_seat_num TEXT;
    v_berth TEXT;
    v_is_win BOOLEAN;
    v_inserted INT := 0;
    i INT;
BEGIN
    -- Acquire transaction-scoped advisory lock specifically on this train, date, and class
    PERFORM pg_advisory_xact_lock(hashtext('seats_init:' || p_train_id || ':' || p_travel_date::text || ':' || p_class_code));

    -- Fast-path return if seats already exist
    IF EXISTS (
        SELECT 1 FROM public.seats
        WHERE train_id = p_train_id AND travel_date = p_travel_date AND class_code = p_class_code
    ) THEN
        RETURN 0;
    END IF;

    -- Match SEATS_LAYOUT_CONFIG exactly
    CASE p_class_code
        WHEN '1A' THEN v_total_seats := 8;  v_seats_per_row := 4;
        WHEN '2A' THEN v_total_seats := 16; v_seats_per_row := 8;
        WHEN '3A' THEN v_total_seats := 32; v_seats_per_row := 8;
        WHEN '3E' THEN v_total_seats := 32; v_seats_per_row := 8;
        WHEN 'CC' THEN v_total_seats := 20; v_seats_per_row := 5;
        WHEN 'EC' THEN v_total_seats := 8;  v_seats_per_row := 4;
        WHEN 'SL' THEN v_total_seats := 24; v_seats_per_row := 8;
        WHEN '2S' THEN v_total_seats := 24; v_seats_per_row := 6;
        ELSE v_total_seats := 24; v_seats_per_row := 8;
    END CASE;

    FOR i IN 1..v_total_seats
    LOOP
        v_seat_num := p_class_code || '-' || i;
        v_berth := v_berth_types[((i - 1) % v_berth_count) + 1];
        v_is_win := (((i - 1) % v_seats_per_row) IN (0, v_seats_per_row - 1));

        INSERT INTO public.seats (
            train_id, travel_date, class_code, seat_number, berth_type, is_window, is_booked
        ) VALUES (
            p_train_id, p_travel_date, p_class_code, v_seat_num, v_berth, v_is_win, FALSE
        )
        ON CONFLICT (train_id, travel_date, class_code, seat_number) DO NOTHING;

        v_inserted := v_inserted + 1;
    END LOOP;

    RETURN v_inserted;
END;
$$;

-- Function 8B: Authoritative Fare Calculation Engine (Strict Validations, Zero Silent Defaults)
CREATE OR REPLACE FUNCTION public.calculate_authoritative_fare_sql(
    p_train_id TEXT,
    p_travel_class TEXT,
    p_quota TEXT,
    p_num_passengers INT
)
RETURNS NUMERIC(10, 2)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_base NUMERIC(10, 2);
    v_available_classes JSONB;
    v_mult NUMERIC(5, 2);
    v_surch NUMERIC(5, 2);
    v_fare_per_pax NUMERIC(10, 2);
    v_res_fee NUMERIC(10, 2) := 40.00;
BEGIN
    -- 1. Validate Passenger Count
    IF p_num_passengers IS NULL OR p_num_passengers < 1 OR p_num_passengers > 6 THEN
        RAISE EXCEPTION 'Invalid passenger count (%). Must be between 1 and 6.', p_num_passengers;
    END IF;

    -- 2. Validate Train and Retrieve Authoritative Base Fare & Classes
    SELECT fare_base, available_classes INTO v_base, v_available_classes
    FROM public.trains
    WHERE id = p_train_id;

    IF v_base IS NULL THEN
        RAISE EXCEPTION 'Invalid train ID "%": train does not exist in catalog.', p_train_id;
    END IF;

    -- 3. Validate Travel Class Offered on Train
    IF p_travel_class IS NULL OR NOT (v_available_classes ? p_travel_class) THEN
        RAISE EXCEPTION 'Invalid travel class "%": not offered on train %.', p_travel_class, p_train_id;
    END IF;

    v_mult := CASE p_travel_class
        WHEN '1A' THEN 3.20
        WHEN '2A' THEN 2.10
        WHEN '3A' THEN 1.50
        WHEN '3E' THEN 1.35
        WHEN 'CC' THEN 1.25
        WHEN 'EC' THEN 2.30
        WHEN 'SL' THEN 1.00
        WHEN '2S' THEN 0.45
        ELSE NULL
    END;

    IF v_mult IS NULL THEN
        RAISE EXCEPTION 'Unknown multiplier for travel class "%".', p_travel_class;
    END IF;

    -- 4. Validate Booking Quota (Strict: no silent fallback to GN)
    IF p_quota IS NULL THEN
        RAISE EXCEPTION 'Booking quota cannot be null. Supported quotas are GN, TQ, PT, LD.';
    END IF;

    v_surch := CASE p_quota
        WHEN 'GN' THEN 0.00
        WHEN 'LD' THEN 0.00
        WHEN 'TQ' THEN 0.25
        WHEN 'PT' THEN 0.45
        ELSE NULL
    END;

    IF v_surch IS NULL THEN
        RAISE EXCEPTION 'Invalid booking quota "%". Supported quotas are GN, TQ, PT, LD.', p_quota;
    END IF;

    v_fare_per_pax := ROUND((v_base * v_mult) * (1.00 + v_surch));
    RETURN (v_fare_per_pax + v_res_fee) * p_num_passengers;
END;
$$;

-- Function 8C: Atomic Seat Locking (Enforces Valid Session, Rejects Missing Seats & Validates Inputs)
CREATE OR REPLACE FUNCTION public.lock_seats_atomic(
    p_train_id TEXT,
    p_travel_date DATE,
    p_class_code TEXT,
    p_seat_numbers TEXT[],
    p_session_token TEXT,
    p_lock_seconds INT DEFAULT 300
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_locked_until TIMESTAMPTZ;
    v_distinct_seats TEXT[];
    v_requested_count INT;
    v_locked_count INT := 0;
    v_already_booked_seat TEXT;
    v_already_locked_seat TEXT;
    v_available_classes JSONB;
    v_session_user_id BIGINT;
    v_is_revoked BOOLEAN;
    v_session_expires_at TIMESTAMPTZ;
    v_last_active TIMESTAMPTZ;
BEGIN
    -- 1. Input Validations
    IF p_session_token IS NULL OR trim(p_session_token) = '' THEN
        RETURN jsonb_build_object('success', false, 'error', 'Active session token is required.');
    END IF;
    IF p_train_id IS NULL OR trim(p_train_id) = '' THEN
        RETURN jsonb_build_object('success', false, 'error', 'Train ID is required.');
    END IF;
    IF p_travel_date IS NULL THEN
        RETURN jsonb_build_object('success', false, 'error', 'Travel date is required.');
    END IF;
    IF p_travel_date < CURRENT_DATE THEN
        RETURN jsonb_build_object('success', false, 'error', 'Travel date cannot be in the past.');
    END IF;
    IF p_travel_date > (CURRENT_DATE + 120) THEN
        RETURN jsonb_build_object('success', false, 'error', 'Travel date exceeds 120-day advance booking window.');
    END IF;
    IF p_class_code IS NULL OR trim(p_class_code) = '' THEN
        RETURN jsonb_build_object('success', false, 'error', 'Class code is required.');
    END IF;
    IF p_seat_numbers IS NULL OR array_length(p_seat_numbers, 1) = 0 THEN
        RETURN jsonb_build_object('success', false, 'error', 'No seats specified.');
    END IF;

    -- 2. Validate Session in public.active_sessions
    SELECT user_id, is_revoked, expires_at, last_active
    INTO v_session_user_id, v_is_revoked, v_session_expires_at, v_last_active
    FROM public.active_sessions
    WHERE session_token = p_session_token;

    IF NOT FOUND THEN
        RETURN jsonb_build_object('success', false, 'error', 'Authentication failed: active session not found.');
    END IF;

    IF v_is_revoked THEN
        RETURN jsonb_build_object('success', false, 'error', 'Authentication failed: session has been revoked.');
    END IF;

    IF v_session_expires_at < NOW() OR v_last_active < (NOW() - INTERVAL '24 hours') THEN
        RETURN jsonb_build_object('success', false, 'error', 'Authentication failed: session has expired. Please log in again.');
    END IF;

    -- 3. Validate Train & Travel Class in public.trains
    SELECT available_classes INTO v_available_classes
    FROM public.trains
    WHERE id = p_train_id;

    IF v_available_classes IS NULL THEN
        RETURN jsonb_build_object('success', false, 'error', 'Invalid train: train ID not found in catalog.');
    END IF;

    IF NOT (v_available_classes ? p_class_code) THEN
        RETURN jsonb_build_object('success', false, 'error', 'Travel class ' || p_class_code || ' is not offered on train ' || p_train_id || '.');
    END IF;

    -- 4. Extract Deduplicated Array of Seat Numbers
    SELECT array_agg(DISTINCT s) INTO v_distinct_seats
    FROM unnest(p_seat_numbers) AS s
    WHERE s IS NOT NULL AND trim(s) <> '';

    v_requested_count := COALESCE(array_length(v_distinct_seats, 1), 0);
    IF v_requested_count = 0 THEN
        RETURN jsonb_build_object('success', false, 'error', 'No valid seat numbers provided.');
    END IF;
    IF v_requested_count > 6 THEN
        RETURN jsonb_build_object('success', false, 'error', 'Cannot lock more than 6 seats per booking.');
    END IF;

    -- Bound lock duration safely between 60s and 900s
    v_locked_until := NOW() + (GREATEST(60, LEAST(COALESCE(p_lock_seconds, 300), 900)) || ' seconds')::interval;

    -- Guarantee seats exist for this train schedule
    PERFORM public.ensure_train_seats_initialized(p_train_id, p_travel_date, p_class_code);

    -- 5. Release Expired Locks for this train run
    UPDATE public.seats
    SET locked_until = NULL, locked_by_session = NULL
    WHERE train_id = p_train_id
      AND travel_date = p_travel_date
      AND class_code = p_class_code
      AND locked_until IS NOT NULL
      AND locked_until < NOW();

    -- 6. Lock individual seat rows with PERFORM FOR UPDATE
    PERFORM 1
    FROM public.seats
    WHERE train_id = p_train_id
      AND travel_date = p_travel_date
      AND class_code = p_class_code
      AND seat_number = ANY(v_distinct_seats)
    FOR UPDATE;

    -- Check if any requested seat is already booked
    SELECT seat_number INTO v_already_booked_seat
    FROM public.seats
    WHERE train_id = p_train_id
      AND travel_date = p_travel_date
      AND class_code = p_class_code
      AND seat_number = ANY(v_distinct_seats)
      AND is_booked = TRUE
    LIMIT 1;

    IF v_already_booked_seat IS NOT NULL THEN
        RETURN jsonb_build_object('success', false, 'error', 'Seat ' || v_already_booked_seat || ' is already booked.');
    END IF;

    -- Check if any seat is locked by another session
    SELECT seat_number INTO v_already_locked_seat
    FROM public.seats
    WHERE train_id = p_train_id
      AND travel_date = p_travel_date
      AND class_code = p_class_code
      AND seat_number = ANY(v_distinct_seats)
      AND locked_until > NOW()
      AND locked_by_session IS DISTINCT FROM p_session_token
    LIMIT 1;

    IF v_already_locked_seat IS NOT NULL THEN
        RETURN jsonb_build_object('success', false, 'error', 'Seat ' || v_already_locked_seat || ' is currently reserved by another traveler. Please choose another seat.');
    END IF;

    -- 7. Atomically apply the lock to all requested seats
    UPDATE public.seats
    SET locked_until = v_locked_until,
        locked_by_session = p_session_token
    WHERE train_id = p_train_id
      AND travel_date = p_travel_date
      AND class_code = p_class_code
      AND seat_number = ANY(v_distinct_seats)
      AND is_booked = FALSE
      AND (locked_until IS NULL OR locked_until <= NOW() OR locked_by_session = p_session_token);

    GET DIAGNOSTICS v_locked_count = ROW_COUNT;

    IF v_locked_count <> v_requested_count THEN
        RAISE EXCEPTION 'Lock acquisition conflict: could only lock % of % requested seats.', v_locked_count, v_requested_count;
    END IF;

    RETURN jsonb_build_object(
        'success', true,
        'lockedSeats', v_distinct_seats,
        'lockedUntil', v_locked_until,
        'expiresIn', EXTRACT(EPOCH FROM (v_locked_until - NOW()))::int
    );
END;
$$;

-- Function 8D: Atomic Booking Creation (Authoritative Train Info, Session Security & Payment-Pending Status)
CREATE OR REPLACE FUNCTION public.create_booking_atomic(
    p_user_id BIGINT,
    p_session_token TEXT,
    p_pnr TEXT,
    p_booking_ref TEXT,
    p_train_id TEXT,
    p_travel_class TEXT,
    p_travel_date DATE,
    p_quota TEXT,
    p_claimed_fare NUMERIC,
    p_contact_mobile TEXT,
    p_contact_email TEXT,
    p_seat_numbers TEXT[],
    p_passengers JSONB
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_booking_id BIGINT;
    v_distinct_seats TEXT[];
    v_seat_count INT := 0;
    v_pax_count INT;
    v_conflicting_seat TEXT;
    v_found_count INT;
    v_authoritative_fare NUMERIC(10, 2);
    v_pax JSONB;
    v_pax_name TEXT;
    v_pax_age INT;
    v_updated_seats_count INT;
    v_train_number TEXT;
    v_train_name TEXT;
    v_source_station TEXT;
    v_dest_station TEXT;
    v_departure_time TEXT;
    v_arrival_time TEXT;
    v_available_classes JSONB;
    v_session_user_id BIGINT;
    v_is_revoked BOOLEAN;
    v_session_expires_at TIMESTAMPTZ;
    v_last_active TIMESTAMPTZ;
BEGIN
    -- 1. Input Validations
    IF p_session_token IS NULL OR trim(p_session_token) = '' THEN
        RETURN jsonb_build_object('success', false, 'error', 'Active session token is required.');
    END IF;
    IF p_pnr IS NULL OR trim(p_pnr) = '' THEN
        RETURN jsonb_build_object('success', false, 'error', 'PNR number is required.');
    END IF;
    IF p_booking_ref IS NULL OR trim(p_booking_ref) = '' THEN
        RETURN jsonb_build_object('success', false, 'error', 'Booking reference is required.');
    END IF;

    -- 2. Validate Session & User Ownership
    SELECT user_id, is_revoked, expires_at, last_active
    INTO v_session_user_id, v_is_revoked, v_session_expires_at, v_last_active
    FROM public.active_sessions
    WHERE session_token = p_session_token;

    IF NOT FOUND THEN
        RETURN jsonb_build_object('success', false, 'error', 'Authentication failed: active session not found.');
    END IF;

    IF v_is_revoked THEN
        RETURN jsonb_build_object('success', false, 'error', 'Authentication failed: session has been revoked.');
    END IF;

    IF v_session_expires_at < NOW() OR v_last_active < (NOW() - INTERVAL '24 hours') THEN
        RETURN jsonb_build_object('success', false, 'error', 'Authentication failed: session has expired. Please sign in again.');
    END IF;

    IF v_session_user_id IS DISTINCT FROM p_user_id THEN
        RETURN jsonb_build_object('success', false, 'error', 'Authorization failed: session user does not match booking user.');
    END IF;

    -- 3. Retrieve Authoritative Train Schedule Details
    SELECT train_number, train_name, source_station, dest_station, departure_time, arrival_time, available_classes
    INTO v_train_number, v_train_name, v_source_station, v_dest_station, v_departure_time, v_arrival_time, v_available_classes
    FROM public.trains
    WHERE id = p_train_id;

    IF v_train_number IS NULL THEN
        RETURN jsonb_build_object('success', false, 'error', 'Train ID ' || p_train_id || ' not found in catalog.');
    END IF;

    IF NOT (v_available_classes ? p_travel_class) THEN
        RETURN jsonb_build_object('success', false, 'error', 'Travel class ' || p_travel_class || ' is not offered on train ' || p_train_id || '.');
    END IF;

    -- 4. Validate Booking Quota
    IF p_quota IS NULL OR p_quota NOT IN ('GN', 'TQ', 'PT', 'LD') THEN
        RETURN jsonb_build_object('success', false, 'error', 'Invalid booking quota. Supported quotas are GN, TQ, PT, LD.');
    END IF;

    -- 5. Validate Passengers List
    IF p_passengers IS NULL OR jsonb_typeof(p_passengers) <> 'array' THEN
        RETURN jsonb_build_object('success', false, 'error', 'Invalid passenger list format.');
    END IF;
    v_pax_count := jsonb_array_length(p_passengers);
    IF v_pax_count < 1 OR v_pax_count > 6 THEN
        RETURN jsonb_build_object('success', false, 'error', 'Booking must contain between 1 and 6 passengers.');
    END IF;

    FOR v_pax IN SELECT * FROM jsonb_array_elements(p_passengers)
    LOOP
        v_pax_name := trim(COALESCE(v_pax->>'name', ''));
        IF v_pax_name = '' THEN
            RETURN jsonb_build_object('success', false, 'error', 'All passengers must have a valid non-empty name.');
        END IF;
        BEGIN
            v_pax_age := (v_pax->>'age')::int;
        EXCEPTION WHEN OTHERS THEN
            RETURN jsonb_build_object('success', false, 'error', 'Invalid age for passenger: ' || v_pax_name);
        END;
        IF v_pax_age < 0 OR v_pax_age > 125 THEN
            RETURN jsonb_build_object('success', false, 'error', 'Passenger age must be between 0 and 125.');
        END IF;
    END LOOP;

    -- 6. Validate Seats & Lock Ownership
    IF p_seat_numbers IS NULL OR array_length(p_seat_numbers, 1) = 0 THEN
        RETURN jsonb_build_object('success', false, 'error', 'Seat allocation is required.');
    END IF;

    SELECT array_agg(DISTINCT s) INTO v_distinct_seats
    FROM unnest(p_seat_numbers) AS s
    WHERE s IS NOT NULL AND trim(s) <> '';

    v_seat_count := COALESCE(array_length(v_distinct_seats, 1), 0);

    IF v_seat_count <> array_length(p_seat_numbers, 1) THEN
        RETURN jsonb_build_object('success', false, 'error', 'Duplicate seat numbers detected in booking request.');
    END IF;

    IF v_seat_count <> v_pax_count THEN
        RETURN jsonb_build_object(
            'success', false,
            'error', 'Number of allocated seats (' || v_seat_count || ') does not match passenger count (' || v_pax_count || ').'
        );
    END IF;

    -- Lock individual seat rows using PERFORM FOR UPDATE
    PERFORM 1
    FROM public.seats
    WHERE train_id = p_train_id
      AND travel_date = p_travel_date
      AND class_code = p_travel_class
      AND seat_number = ANY(v_distinct_seats)
    FOR UPDATE;

    GET DIAGNOSTICS v_found_count = ROW_COUNT;

    IF v_found_count <> v_seat_count THEN
        RETURN jsonb_build_object('success', false, 'error', 'One or more selected seats do not exist in inventory.');
    END IF;

    -- Verify none are already booked
    SELECT seat_number INTO v_conflicting_seat
    FROM public.seats
    WHERE train_id = p_train_id
      AND travel_date = p_travel_date
      AND class_code = p_travel_class
      AND seat_number = ANY(v_distinct_seats)
      AND is_booked = TRUE
    LIMIT 1;

    IF v_conflicting_seat IS NOT NULL THEN
        RETURN jsonb_build_object('success', false, 'error', 'Seat ' || v_conflicting_seat || ' is already booked.');
    END IF;

    -- Verify active lock ownership
    SELECT seat_number INTO v_conflicting_seat
    FROM public.seats
    WHERE train_id = p_train_id
      AND travel_date = p_travel_date
      AND class_code = p_travel_class
      AND seat_number = ANY(v_distinct_seats)
      AND (
          (locked_until IS NULL OR locked_until < NOW())
          OR (locked_by_session IS DISTINCT FROM p_session_token)
      )
    LIMIT 1;

    IF v_conflicting_seat IS NOT NULL THEN
        RETURN jsonb_build_object(
            'success', false,
            'error', 'Lock on seat ' || v_conflicting_seat || ' has expired or is held by another traveler. Please re-lock your seats.'
        );
    END IF;

    -- 7. Calculate Authoritative Fare Server-Side
    v_authoritative_fare := public.calculate_authoritative_fare_sql(
        p_train_id, p_travel_class, p_quota, v_pax_count
    );

    IF p_claimed_fare IS NOT NULL AND ABS(p_claimed_fare - v_authoritative_fare) > 1.00 THEN
        RETURN jsonb_build_object(
            'success', false,
            'error', 'Fare mismatch detected. Authoritative fare is ' || v_authoritative_fare || ', but claimed fare was ' || p_claimed_fare || '.'
        );
    END IF;

    -- 8. Insert Booking Record (Status is strictly PAYMENT_PENDING)
    INSERT INTO public.bookings (
        pnr, user_id, booking_ref, train_id, train_number, train_name,
        source_station, dest_station, departure_time, arrival_time,
        travel_class, travel_date, quota, total_fare, status,
        contact_mobile, contact_email
    ) VALUES (
        p_pnr, p_user_id, p_booking_ref, p_train_id, v_train_number, v_train_name,
        v_source_station, v_dest_station, v_departure_time, v_arrival_time,
        p_travel_class, p_travel_date, p_quota, v_authoritative_fare, 'PAYMENT_PENDING',
        NULLIF(trim(p_contact_mobile), ''), NULLIF(trim(p_contact_email), '')
    ) RETURNING id INTO v_booking_id;

    -- 9. Insert Passenger Records (Initial status is HOLD)
    FOR v_pax IN SELECT * FROM jsonb_array_elements(p_passengers)
    LOOP
        INSERT INTO public.passengers (
            booking_id, name, age, gender, berth_choice, seat_allocated, status
        ) VALUES (
            v_booking_id,
            trim(v_pax->>'name'),
            (v_pax->>'age')::int,
            COALESCE(v_pax->>'gender', 'M'),
            COALESCE(v_pax->>'berth_choice', 'NO_PREF'),
            v_pax->>'seat_allocated',
            'HOLD'
        );
    END LOOP;

    -- 10. Finalize Seats: Transition from Locked to Booked Atomically
    WITH updated AS (
        UPDATE public.seats
        SET is_booked = TRUE,
            booking_id = v_booking_id,
            locked_until = NULL,
            locked_by_session = NULL
        WHERE train_id = p_train_id
          AND travel_date = p_travel_date
          AND class_code = p_travel_class
          AND seat_number = ANY(v_distinct_seats)
          AND is_booked = FALSE
          AND locked_by_session = p_session_token
        RETURNING seat_number
    )
    SELECT count(*) INTO v_updated_seats_count FROM updated;

    IF v_updated_seats_count <> v_seat_count THEN
        RAISE EXCEPTION 'Concurrency conflict: Only % of % seats could be finalized for booking.', v_updated_seats_count, v_seat_count;
    END IF;

    RETURN jsonb_build_object(
        'success', true,
        'pnr', p_pnr,
        'bookingId', v_booking_id,
        'bookingRef', p_booking_ref,
        'totalFare', v_authoritative_fare,
        'status', 'PAYMENT_PENDING'
    );
END;
$$;

-- Function 8E: Atomic Booking Cancellation (Releases Booked Seats Back to Available Inventory)
CREATE OR REPLACE FUNCTION public.cancel_booking_atomic(
    p_pnr TEXT,
    p_user_id BIGINT,
    p_session_token TEXT,
    p_is_admin BOOLEAN DEFAULT FALSE
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_booking_id BIGINT;
    v_status TEXT;
    v_booking_user_id BIGINT;
    v_released_seats INT := 0;
BEGIN
    IF p_pnr IS NULL OR trim(p_pnr) = '' THEN
        RETURN jsonb_build_object('success', false, 'error', 'Valid PNR required for cancellation.');
    END IF;

    -- Verify session for non-admin callers
    IF NOT p_is_admin THEN
        IF p_session_token IS NULL OR trim(p_session_token) = '' THEN
            RETURN jsonb_build_object('success', false, 'error', 'Active session token required.');
        END IF;
        IF NOT EXISTS (
            SELECT 1 FROM public.active_sessions
            WHERE session_token = p_session_token
              AND user_id = p_user_id
              AND is_revoked = FALSE
              AND expires_at > NOW()
        ) THEN
            RETURN jsonb_build_object('success', false, 'error', 'Authentication failed or session expired.');
        END IF;
    END IF;

    -- Lock booking row for update
    SELECT id, user_id, status INTO v_booking_id, v_booking_user_id, v_status
    FROM public.bookings
    WHERE pnr = p_pnr
    FOR UPDATE;

    IF v_booking_id IS NULL THEN
        RETURN jsonb_build_object('success', false, 'error', 'Booking with PNR ' || p_pnr || ' not found.');
    END IF;

    IF NOT p_is_admin AND v_booking_user_id <> p_user_id THEN
        RETURN jsonb_build_object('success', false, 'error', 'Unauthorized: you do not own this booking.');
    END IF;

    IF v_status = 'CANCELLED' THEN
        RETURN jsonb_build_object('success', false, 'error', 'Booking is already cancelled.');
    END IF;

    -- Update booking status
    UPDATE public.bookings
    SET status = 'CANCELLED'
    WHERE id = v_booking_id;

    -- Update passengers status
    UPDATE public.passengers
    SET status = 'CAN'
    WHERE booking_id = v_booking_id;

    -- Release booked seats back into available inventory
    UPDATE public.seats
    SET is_booked = FALSE,
        booking_id = NULL,
        locked_until = NULL,
        locked_by_session = NULL
    WHERE booking_id = v_booking_id;

    GET DIAGNOSTICS v_released_seats = ROW_COUNT;

    RETURN jsonb_build_object(
        'success', true,
        'pnr', p_pnr,
        'bookingId', v_booking_id,
        'status', 'CANCELLED',
        'releasedSeats', v_released_seats,
        'message', 'Booking successfully cancelled and inventory released.'
    );
END;
$$;

-- Function 8F: Atomic Registration Verification Token Consumption
