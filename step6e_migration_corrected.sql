-- Function 8H: Cleanup Expired Seat Locks and Expired Pending Bookings
-- Releases temporary checkout locks AND safely cancels uninitiated checkout sessions older than 15 mins.
-- Bookings with active in-flight gateway payments are protected with an extended 30-minute grace window.
CREATE OR REPLACE FUNCTION public.cleanup_expired_seat_locks()
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_cleaned_count INTEGER := 0;
    v_expired_seats_count INTEGER := 0;
    v_abandoned_ids BIGINT[];
    v_timedout_ids BIGINT[];
    v_all_expired_ids BIGINT[] := '{}';
BEGIN
    -- 1. Release temporary checkout locks that have expired
    UPDATE public.seats
    SET locked_until = NULL,
        locked_by_session = NULL
    WHERE is_booked = FALSE
      AND locked_until IS NOT NULL
      AND locked_until < NOW();

    GET DIAGNOSTICS v_cleaned_count = ROW_COUNT;

    -- 2. Identify abandoned checkouts: payment was NEVER initiated and 15 minutes elapsed
    WITH abandoned_bookings AS (
        UPDATE public.bookings
        SET status = 'CANCELLED'
        WHERE status = 'PAYMENT_PENDING'
          AND payment_gateway_ref IS NULL
          AND payment_initiated_at IS NULL
          AND created_at < (NOW() - INTERVAL '15 minutes')
        RETURNING id
    )
    SELECT array_agg(id) INTO v_abandoned_ids FROM abandoned_bookings;

    IF v_abandoned_ids IS NOT NULL THEN
        v_all_expired_ids := v_all_expired_ids || v_abandoned_ids;
    END IF;

    -- 3. Identify timed-out gateway payments: payment was initiated but webhook never confirmed after 30 minutes
    WITH timed_out_payments AS (
        UPDATE public.bookings
        SET status = 'CANCELLED'
        WHERE status IN ('PAYMENT_PENDING', 'PAYMENT_PROCESSING')
          AND (payment_gateway_ref IS NOT NULL OR payment_initiated_at IS NOT NULL)
          AND created_at < (NOW() - INTERVAL '30 minutes')
        RETURNING id
    )
    SELECT array_agg(id) INTO v_timedout_ids FROM timed_out_payments;

    IF v_timedout_ids IS NOT NULL THEN
        v_all_expired_ids := v_all_expired_ids || v_timedout_ids;
    END IF;

    -- 4. Transition passengers to 'CAN' and release seats
    IF array_length(v_all_expired_ids, 1) > 0 THEN
        UPDATE public.passengers
        SET status = 'CAN'
        WHERE booking_id = ANY(v_all_expired_ids);

        UPDATE public.seats
        SET is_booked = FALSE,
            booking_id = NULL,
            locked_until = NULL,
            locked_by_session = NULL
        WHERE booking_id = ANY(v_all_expired_ids);

        GET DIAGNOSTICS v_expired_seats_count = ROW_COUNT;
    END IF;

    RETURN v_cleaned_count + v_expired_seats_count;
END;
$$;

