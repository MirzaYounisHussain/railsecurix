-- Function 8J: Authoritative Payment Webhook Reconciliation & Traveler Fund Protection
-- Safely processes server-verified payment gateway webhooks.
-- Rejects any untrusted or direct caller without valid gateway authentication.
-- If a confirmation is delayed and arrives after booking cancellation, flags REFUND_PENDING
-- so money is never silently lost and an automatic refund can be processed without reallocating released seats.
CREATE OR REPLACE FUNCTION public.reconcile_payment_webhook_atomic(
    p_booking_ref TEXT,
    p_gateway_txn_id TEXT,
    p_payment_status TEXT,
    p_verified_amount NUMERIC,
    p_is_trusted_gateway_caller BOOLEAN DEFAULT FALSE
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_booking_id BIGINT;
    v_total_fare NUMERIC(10, 2);
    v_current_status TEXT;
    v_existing_ref TEXT;
BEGIN
    -- 1. Trust verification: Reject any untrusted or direct caller
    IF p_is_trusted_gateway_caller IS NOT TRUE THEN
        RETURN jsonb_build_object('success', false, 'error', 'Reconciliation rejected: trusted server-side gateway authentication required.');
    END IF;

    -- 2. Input validation
    IF p_booking_ref IS NULL OR trim(p_booking_ref) = '' THEN
        RETURN jsonb_build_object('success', false, 'error', 'Booking reference required.');
    END IF;

    IF p_gateway_txn_id IS NULL OR trim(p_gateway_txn_id) = '' 
       OR UPPER(trim(p_gateway_txn_id)) IN ('SIMULATED', 'TEST', 'DUMMY', 'PENDING_GATEWAY_SETTLEMENT', 'NULL', 'UNDEFINED') THEN
        RETURN jsonb_build_object('success', false, 'error', 'A valid non-placeholder gateway transaction ID is required.');
    END IF;

    IF p_payment_status NOT IN ('SUCCESS', 'FAILED') THEN
        RETURN jsonb_build_object('success', false, 'error', 'Payment status must be SUCCESS or FAILED.');
    END IF;

    -- 3. Lock booking row for update
    SELECT id, total_fare, status, payment_gateway_ref 
    INTO v_booking_id, v_total_fare, v_current_status, v_existing_ref
    FROM public.bookings
    WHERE booking_ref = p_booking_ref
    FOR UPDATE;

    IF v_booking_id IS NULL THEN
        RETURN jsonb_build_object('success', false, 'error', 'Booking reference not found.');
    END IF;

    -- 4. Replay Safeguard across different bookings:
    -- Verify that p_gateway_txn_id has not already been used on another booking
    IF EXISTS (
        SELECT 1 FROM public.bookings 
        WHERE payment_gateway_ref = p_gateway_txn_id AND id != v_booking_id
    ) THEN
        RETURN jsonb_build_object(
            'success', false,
            'error', 'Replay detected: gateway transaction ID has already been credited to another booking.'
        );
    END IF;

    -- 5. Handle gateway payment failure
    IF p_payment_status = 'FAILED' THEN
        -- An already confirmed booking CANNOT be cancelled by a late or out-of-order FAILED webhook
        IF v_current_status = 'CONFIRMED' THEN
            RETURN jsonb_build_object(
                'success', false,
                'error', 'Invalid transition: cannot cancel an already confirmed booking with a failed payment webhook.',
                'status', 'CONFIRMED'
            );
        END IF;

        IF v_current_status IN ('CANCELLED', 'REFUND_PENDING') THEN
            RETURN jsonb_build_object('success', true, 'status', v_current_status, 'alreadyTerminal', true);
        END IF;

        -- Safe failure transition from pending states
        UPDATE public.bookings
        SET status = 'CANCELLED',
            payment_gateway_ref = p_gateway_txn_id
        WHERE id = v_booking_id;

        UPDATE public.passengers SET status = 'CAN' WHERE booking_id = v_booking_id;

        UPDATE public.seats
        SET is_booked = FALSE, booking_id = NULL, locked_until = NULL, locked_by_session = NULL
        WHERE booking_id = v_booking_id;

        RETURN jsonb_build_object('success', true, 'status', 'CANCELLED', 'message', 'Payment failed; booking cancelled and seats released.');
    END IF;

    -- 6. Handle gateway payment success
    IF p_payment_status = 'SUCCESS' THEN
        -- Idempotency check: if already confirmed with the same transaction ID
        IF v_current_status = 'CONFIRMED' THEN
            IF v_existing_ref = p_gateway_txn_id THEN
                RETURN jsonb_build_object('success', true, 'status', 'CONFIRMED', 'alreadyConfirmed', true);
            ELSE
                RETURN jsonb_build_object('success', false, 'error', 'Conflict: booking already confirmed under a different transaction ID.');
            END IF;
        END IF;

        IF v_current_status = 'REFUND_PENDING' THEN
            RETURN jsonb_build_object('success', true, 'status', 'REFUND_PENDING', 'alreadyFlaggedRefund', true);
        END IF;

        IF ABS(p_verified_amount - v_total_fare) > 1.00 THEN
            RETURN jsonb_build_object('success', false, 'error', 'Amount mismatch: expected ' || v_total_fare || ' but received ' || p_verified_amount);
        END IF;

        -- Normal in-time confirmation
        IF v_current_status IN ('PAYMENT_PENDING', 'PAYMENT_PROCESSING', 'PENDING') THEN
            UPDATE public.bookings
            SET status = 'CONFIRMED',
                payment_gateway_ref = p_gateway_txn_id,
                payment_verified_at = NOW()
            WHERE id = v_booking_id;

            UPDATE public.passengers
            SET status = 'CNF'
            WHERE booking_id = v_booking_id;

            RETURN jsonb_build_object('success', true, 'status', 'CONFIRMED', 'bookingId', v_booking_id);
        END IF;

        -- Delayed confirmation safeguard: booking was cancelled before webhook arrived
        -- Safely flags REFUND_PENDING and records gateway txn ref without reallocating already released seats!
        IF v_current_status = 'CANCELLED' THEN
            UPDATE public.bookings
            SET status = 'REFUND_PENDING',
                payment_gateway_ref = p_gateway_txn_id,
                payment_verified_at = NOW()
            WHERE id = v_booking_id;

            RETURN jsonb_build_object(
                'success', false,
                'status', 'REFUND_PENDING',
                'bookingId', v_booking_id,
                'message', 'Confirmation delayed and booking expired. Flagged for automatic refund to protect traveler funds. Seats were not reallocated.'
            );
        END IF;
    END IF;

    RETURN jsonb_build_object('success', false, 'error', 'Unrecognized payment state transition.');
END;
$$;

